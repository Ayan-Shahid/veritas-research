#!/usr/bin/env python3
"""Create deploy/.env with fresh secrets, or check an existing one.

    python3 deploy/gen-secrets.py           # writes deploy/.env (mode 600); refuses to overwrite
    python3 deploy/gen-secrets.py --check   # validates deploy/.env; exit 1 on any problem

Standard library only. After generating, fill in every CHANGEME line, then run --check.

ANON_KEY / SERVICE_ROLE_KEY are the API keys GoTrue expects (HS256 JWTs signed with
JWT_SECRET, role "anon" / "service_role"). They deliberately have no `sub` and no `aud`, so
the API (app/core/jwt_verify.py) can never mistake one for a user's access token.
SERVICE_ROLE_KEY is admin-level: it never goes into the frontend build.
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
import re
import secrets
import string
import sys
import time
from pathlib import Path

ENV_PATH = Path(__file__).resolve().parent / ".env"

PASSWORDS = ("POSTGRES_PASSWORD", "APP_DB_PASSWORD", "AUTH_DB_PASSWORD", "REDIS_PASSWORD")
ALNUM = string.ascii_letters + string.digits
TEN_YEARS = 10 * 365 * 24 * 3600

TEMPLATE = """\
# Veritas production environment. Generated by gen-secrets.py. Keep this file private (mode 600).

# --- You fill these in -------------------------------------------------------------------------
DOMAIN=veritas.ayandev.app
# Copy the exact image tag from the `auth` service in Supabase's self-hosting compose file:
# https://github.com/supabase/supabase/blob/master/docker/docker-compose.yml  (e.g. supabase/gotrue:v2.196.0)
AUTH_IMAGE=CHANGEME
# Cloudflare Zero Trust > Networks > Tunnels > your tunnel > Docker install command: the token after --token
CLOUDFLARE_TUNNEL_TOKEN=CHANGEME
ANTHROPIC_API_KEY=CHANGEME
# SEC requires a real name and contact email in the User-Agent.
EDGAR_USER_AGENT="Veritas Research CHANGEME@example.com"
# Resend SMTP: the user is literally "resend", the password is a Resend API key (sending access).
SMTP_HOST=smtp.resend.com
SMTP_PORT=465
SMTP_USER=resend
SMTP_PASS=CHANGEME
SMTP_ADMIN_EMAIL=noreply@ayandev.app
SMTP_SENDER_NAME=Veritas

# --- Generated: do not edit (changing JWT_SECRET invalidates both keys and every session) -----
{generated}
"""


def b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def b64url_decode(text: str) -> bytes:
    return base64.urlsafe_b64decode(text + "=" * (-len(text) % 4))


def sign_jwt(claims: dict, secret: str) -> str:
    header = b64url(json.dumps({"alg": "HS256", "typ": "JWT"}, separators=(",", ":")).encode())
    body = b64url(json.dumps(claims, separators=(",", ":")).encode())
    sig = hmac.new(secret.encode(), f"{header}.{body}".encode(), hashlib.sha256).digest()
    return f"{header}.{body}.{b64url(sig)}"


def verify_jwt(token: str, secret: str) -> dict:
    """Returns the claims of a valid HS256 token signed with `secret`, else raises ValueError."""
    try:
        header_b64, body_b64, sig_b64 = token.split(".")
        header = json.loads(b64url_decode(header_b64))
        claims = json.loads(b64url_decode(body_b64))
        sig = b64url_decode(sig_b64)
    except Exception as exc:  # malformed in any way
        raise ValueError("not a JWT") from exc
    if header.get("alg") != "HS256":
        raise ValueError("alg is not HS256")
    expected = hmac.new(secret.encode(), f"{header_b64}.{body_b64}".encode(), hashlib.sha256).digest()
    if not hmac.compare_digest(sig, expected):
        raise ValueError("bad signature")
    if not isinstance(claims, dict):
        raise ValueError("claims are not an object")
    return claims


def api_key(role: str, secret: str, now: int) -> str:
    return sign_jwt({"role": role, "iss": "supabase", "iat": now, "exp": now + TEN_YEARS}, secret)


def password(length: int = 32) -> str:
    # Alphanumeric only: these are embedded in postgres:// and redis:// URLs.
    return "".join(secrets.choice(ALNUM) for _ in range(length))


def generate_values(now: int | None = None) -> dict[str, str]:
    now = int(time.time()) if now is None else now
    values = {name: password() for name in PASSWORDS}
    jwt_secret = secrets.token_hex(32)
    values["JWT_SECRET"] = jwt_secret
    values["ANON_KEY"] = api_key("anon", jwt_secret, now)
    values["SERVICE_ROLE_KEY"] = api_key("service_role", jwt_secret, now)
    values["SECRET_KEY"] = secrets.token_hex(32)
    return values


def render(values: dict[str, str]) -> str:
    return TEMPLATE.format(generated="\n".join(f"{k}={v}" for k, v in values.items()))


def write_env(path: Path = ENV_PATH) -> None:
    text = render(generate_values())
    # O_EXCL: never overwrite an existing file (it holds the secrets your database was created with).
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(text)


def parse_env(text: str) -> dict[str, str]:
    values: dict[str, str] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[key.strip()] = value
    return values


def check(values: dict[str, str]) -> list[str]:
    problems: list[str] = []
    required = ["DOMAIN", "AUTH_IMAGE", "CLOUDFLARE_TUNNEL_TOKEN", "ANTHROPIC_API_KEY", "EDGAR_USER_AGENT",
                "SMTP_HOST", "SMTP_PORT", "SMTP_USER", "SMTP_PASS", "SMTP_ADMIN_EMAIL", "SMTP_SENDER_NAME",
                *PASSWORDS, "JWT_SECRET", "ANON_KEY", "SERVICE_ROLE_KEY", "SECRET_KEY"]
    for key in required:
        if not values.get(key):
            problems.append(f"{key} is missing or empty")
        elif "CHANGEME" in values[key]:
            problems.append(f"{key} still contains CHANGEME")

    for key in PASSWORDS:
        v = values.get(key, "")
        if v and (len(v) < 24 or not all(c in ALNUM for c in v)):
            problems.append(f"{key} must be at least 24 alphanumeric characters")
    pws = [values.get(k) for k in PASSWORDS if values.get(k)]
    if len(set(pws)) != len(pws):
        problems.append("the four passwords must all be different")

    secret = values.get("JWT_SECRET", "")
    if secret and len(secret) < 32:
        problems.append("JWT_SECRET must be at least 32 characters")
    if secret:
        for key, role in (("ANON_KEY", "anon"), ("SERVICE_ROLE_KEY", "service_role")):
            token = values.get(key, "")
            if not token:
                continue
            try:
                claims = verify_jwt(token, secret)
            except ValueError as exc:
                problems.append(f"{key} does not verify against JWT_SECRET ({exc})")
                continue
            if claims.get("role") != role:
                problems.append(f"{key} has role {claims.get('role')!r}, expected {role!r}")
            if "sub" in claims or "aud" in claims:
                problems.append(f"{key} must not carry sub/aud (it would look like a user token)")
            if not isinstance(claims.get("exp"), int) or claims["exp"] < time.time() + 30 * 24 * 3600:
                problems.append(f"{key} expires within 30 days; regenerate it")

    domain = values.get("DOMAIN", "")
    if domain and not re.fullmatch(r"(?=.{1,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}", domain):
        problems.append("DOMAIN must be a bare lowercase hostname (no scheme, port, path or trailing dot)")

    image = values.get("AUTH_IMAGE", "")
    if image and "CHANGEME" not in image and not re.fullmatch(r"supabase/gotrue:v\d+\.\d+\.\d+", image):
        problems.append("AUTH_IMAGE should be a pinned tag like supabase/gotrue:v2.196.0 (never :latest)")

    port = values.get("SMTP_PORT", "")
    if port and port not in {"465", "587", "2465", "2587"}:
        problems.append("SMTP_PORT should be 465 (implicit TLS) or 587 (STARTTLS)")
    return problems


def main(argv: list[str]) -> int:
    if argv == ["--check"]:
        if not ENV_PATH.exists():
            print(f"{ENV_PATH} not found; run without --check first", file=sys.stderr)
            return 1
        mode = ENV_PATH.stat().st_mode & 0o777
        problems = check(parse_env(ENV_PATH.read_text()))
        if mode & 0o077:
            problems.append(f"{ENV_PATH.name} is readable by others (mode {mode:o}); run: chmod 600 {ENV_PATH}")
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        print("OK" if not problems else f"{len(problems)} problem(s)", file=sys.stderr if problems else sys.stdout)
        return 1 if problems else 0
    if argv:
        print(__doc__, file=sys.stderr)
        return 2
    try:
        write_env()
    except FileExistsError:
        print(f"{ENV_PATH} already exists; not overwriting it. Use --check to validate it.", file=sys.stderr)
        return 1
    print(f"Wrote {ENV_PATH} (mode 600). Fill in the CHANGEME lines, then run with --check.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
